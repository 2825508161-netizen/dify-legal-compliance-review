import re


def main(chunk: dict, focus_risk_types: str = "全部") -> dict:
    text = re.sub(r"\s+", " ", str((chunk or {}).get("text") or ""))

    rules = [
        (
            r"格式条款|单方(?:面)?(?:解释|修改|终止|解除)|免责|不承担|概不负责|放弃.*权利",
            "民法典 格式条款 提示说明 免责条款 无效",
        ),
        (
            r"违约|赔偿|责任上限|违约金|延期|逾期|交付|验收|付款|预付款",
            "民法典 合同履行 违约责任 损失赔偿",
        ),
        (
            r"自动续期|续约|有效期|期限|终止|解除",
            "民法典 合同期限 解除权 自动续期",
        ),
        (
            r"管辖|仲裁|争议解决|诉讼",
            "民事诉讼法 协议管辖 实际联系",
        ),
        (
            r"个人信息|隐私|数据|跨境|出境|用户画像|生物识别",
            "个人信息保护法 告知同意 最小必要 处理规则 跨境提供",
        ),
        (
            r"员工|劳动|加班|工资|竞业|解除劳动|试用期",
            "劳动合同法 劳动用工 工资 加班 解除 竞业限制",
        ),
        (
            r"广告|宣传|第一|最佳|国家级|保证收益|绝对化",
            "广告法 虚假广告 绝对化用语",
        ),
        (
            r"著作权|商标|专利|知识产权|源代码|成果归属",
            "著作权法 商标法 知识产权 权利归属 侵权责任",
        ),
        (
            r"回扣|佣金|招待|礼品|反腐败|商业贿赂",
            "反不正当竞争法 商业贿赂",
        ),
        (
            r"洗钱|客户身份|受益所有人|可疑交易",
            "反洗钱法 客户尽职调查 可疑交易",
        ),
    ]

    matched = [query for pattern, query in rules if re.search(pattern, text)]
    focus = re.sub(r"[，、；;|/]+", " ", str(focus_risk_types or ""))

    if not matched:
        matched = ["民法典 合同权利义务 违约责任 法律合规"]

    # 关键词检索不应把整段原文塞进 query。保留少量风险主题即可，
    # 避免长查询稀释法条关键词，导致 records 为空。
    query = "；".join(dict.fromkeys(matched))
    if focus and focus != "全部":
        query = f"{query}；关注 {focus[:80]}"

    return {"query": query[:500]}
